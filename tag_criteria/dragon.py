# -*- coding: utf-8 -*-
"""#dragon - dragons and dragon transformations. Require 2+ markers."""
import re

import _common

TAG = "dragon"

PATTERNS = [
    r"дракон", r"драконий", r"драконья", r"драконье",
    r"превратился в дракона", r"превращается в дракона", r"драконья форма",
    r"в облике дракона", r"драконий облик", r"драконья чешуя", r"драконьи крылья",
    r"полудракон", r"полу-дракон", r"драконья трансформация", r"драконья природа",
    r"дракон-оборотень", r"оборотень-дракон",
]


def check(text):
    if not text:
        return False
    # Все паттерны — формы слова «дракон», то есть один маркер.
    # Поэтому порог не по разным маркерам, а по числу упоминаний:
    # разовая метафора темой заметки не делает.
    # Порог 8 подобран по данным: где дракон — тема, упоминаний 19+;
    # где побочная деталь среди прочих превращений — 7 и меньше.
    return _common.count_occurrences(PATTERNS, text) >= 8
