# -*- coding: utf-8 -*-
"""#time_travel - time travel."""
import re

import _common

TAG = "time_travel"

# Общие обороты убраны 09.08.2026: «из прошлого», «в прошлое» и «когда
# вернулся» держали тег в 130 заметках, а выборка из двадцати дала 20 ложных
# срабатываний — метафоры («эхо из прошлого»), флешбэки («разум погрузился
# в прошлое»), реинкарнация («тело из прошлого мира») и разговор о сюжете
# («не надо из прошлого ответа указывать пункты»). «Когда вернулся» ловило
# возвращение из космоса и из мёртвых.
#
# «в будущее» убрано следом за «в прошлое»: оно ловит ту же метафору
# прогресса — «постепенно, сами того не понимая, входили в будущее» (833).
#
# «из другого времени» и «в другом времени» убраны 14.08.2026. Сплошной
# просмотр всех срабатываний дал восемь заметок на этих двух паттернах
# (169.2, 196, 376.1, 471, 516, 538, 918, 943) — и все восемь метафора про
# внешность или голос: «портрет из другого времени», «его лицо, но из другого
# времени», «крик из другого времени», «движением, отточенным в другом
# времени». Ни одной настоящей: там, где перенос действительно есть (959),
# рядом всегда стоит явный маркер.
PATTERNS = [
    r"путешествие во времени", r"путешественник во времени",
    r"путешеству\w* во времени", r"перемещ\w* во времени",
    r"вернулся в прошлое", r"попал в прошлое", r"попадает в прошлое",
    r"отправ\w+ в прошлое", r"перенесся в прошлое", r"перенёсся в прошлое",
    r"перенеслась в прошлое", r"переносится в прошлое",
    r"на \w+ лет в прошлое", r"пропал во времени", r"застрял во времени",
    r"исчез во времени", r"машина времени", r"временной парадокс",
    r"тайм-травел", r"таймтравел",
    r"time[- ]travel", r"когда попал в прошлое",
]

# «Из будущего» — маркер слабый. Сюжетом он бывает («Робин из будущего»,
# 956 и 994), но ровно так же звучит шутка про вид прибора («микроволновка
# из будущего», 204), перечисление типовых поворотов («умер, воскрес,
# вернулся из будущего», 862) и ссылка на название чужой ветки (957).
# Отличает их частота: у настоящих 12 и 4 вхождения, у всех шести ложных —
# одно-два. Поэтому в одиночку он засчитывается только от трёх раз.
WEAK_PATTERNS = [r"из будущего"]
WEAK_MIN = 3

PAT = _common.compile_any(PATTERNS)


def check(text):
    if not text:
        return False
    if _common.live_hits(PATTERNS, text):
        return True
    return _common.live_hits(WEAK_PATTERNS, text) >= WEAK_MIN
