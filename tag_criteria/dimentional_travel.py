# -*- coding: utf-8 -*-
"""#dimentional_travel - dimensional travel, alternate worlds. Require 2+ markers.

Голые основы «альтернативн» и «параллельн» убраны (27.10.2026, разбор
`Reports/dimentional_travel_check.md`). В заметках они почти всегда про
замысел, а не про миры: «альтернативная глава / версия / идея / сюжет»,
наречие «параллельно». В помеченных заметках рядом с миром стоит лишь каждое
пятое вхождение: 217 из 1103 у «альтернативн», 44 из 254 у «параллельн».
На «план альтернативной истории» тег получил `373.6`. Теперь оба слова
считаются, только если рядом мир, вселенная, реальность или измерение (одно
слово между — «альтернативной временной реальности»), а у «альтернативн» ещё
двойник и «альтернативный себя».

Чтобы не потерять настоящие путешествия, где второй маркер звучал иначе,
добавлены: «другая / иная реальность» (один маркер на обе формы — иначе одна
догадка «иная ли это реальность или другая» проходила порог сама), «в
следующий / соседний мир», «по мирам», «в каждом мире», «вернуться в свой мир».
«В свой мир» без глагола не годится: «погружённый в свой мир дисциплины».
"""
import re

import _common

TAG = "dimentional_travel"

# Слово мира, к которому должны относиться «альтернативн» и «параллельн».
_WORLD = r"(?:мир|вселенн|реальност|измерени)"

PATTERNS = [
    r"другой мир", r"иной мир", r"другая вселенная", r"иная вселенная",
    r"альтернативн\w*\s+(?:\w+\s+)?(?:мир|вселенн|реальност|измерени|двойник|себя|я\b)",
    r"параллельн\w*\s+(?:\w+\s+)?" + _WORLD,
    r"(?:друг|ин)\w*\s+реальност",
    r"портал", r"измерение", r"измерения",
    r"между измерениями", r"мультивселенная", r"мультиверс",
    r"попал в мир", r"попала в мир", r"попали в мир", r"перешел в мир",
    r"оказался в другом мире", r"занесло в другой мир", r"между мирами",
    r"из другого мира", r"в другом мире", r"попаданц", r"dimensional travel",
    r"путешествие между мирами",
    r"(?:в|из)\s+(?:следующ|соседн)\w*\s+мир", r"по\s+мирам",
    r"в\s+каждом\s+(?:новом\s+)?мире",
    r"верн\w*\s+(?:\w+\s+)?(?:в|домой\s+в)\s+(?:свой|родной)\s+мир",
]


def check(text):
    if not text:
        return False
    return _common.count_distinct(PATTERNS, text) >= 2
