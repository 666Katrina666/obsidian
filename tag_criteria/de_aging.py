# -*- coding: utf-8 -*-
"""#de-aging - омоложение, взрослый в детском теле.

Устройство: основной маркер обязателен. Описание возраста («мальчик лет
двенадцати», «выглядит на 14») сам по себе тег не даёт — он относится к
кому угодно, включая случайного прохожего:

    159. Split Reality — «Маленький мальчик, лет семи, споткнулся
    неподалёку и рухнул на асфальт»

Из 91 заметки, которые проходили по одному лишь возрасту, 86 не имели ни
одного основного маркера. Часть из них по смыслу про омоложение («его
призрачная форма — подросток лет двенадцати»), но отличить это от
прохожего можно только по тому, о ком речь, а не по словам.
"""
import re

import _common

TAG = "de-aging"

# Прямо про омоложение — одного достаточно.
CORE = [
    r"омолож",
    r"в ребенка", r"в детей",
    r"превратился в ребенка", r"превратили в ребенка", r"превращается в ребёнка",
    r"стал ребёнком", r"стал ребенком",
    r"вечный ребенок", r"вечный ребёнок",
    r"остановил старение", r"остановило старение", r"остановить старение",
    r"детское тело", r"тело ребенка", r"в теле ребенка",
    r"возрастной регресс", r"регресс в детство", r"регресс\w*\s+возраст",
    r"de-aging", r"де-эйджинг",
    r"взрослый в теле ребенка", r"застрял в детском теле",
    r"не растет", r"не растёт",
]

# Возраст: подтверждает основной маркер, но сам по себе не работает.
# «свои N лет» исключены — это как раз НЕ омоложение.
AGE = [
    r"выглядит\s+(?!на\s+свои)на\s+(?:[2-9]|1[0-6])(?:\s*[-–]\s*\d+)?\s*(?:лет|год)?",
    r"выглядит\s+на\s+возраст\s+смерти",
    r"лет\s+(?:[2-9]|1[0-6])\b",
    r"лет\s+(?:двух|трёх|трех|четырёх|четырех|пяти|шести|семи|восьми|девяти"
    r"|десяти|одиннадцати|двенадцати|тринадцати|четырнадцати|пятнадцати|шестнадцати)",
]


def check(text):
    if not text:
        return False
    return _common.search_any(CORE, text)
