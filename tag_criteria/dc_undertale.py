"""#dc/undertale - кроссовер DC с Undertale.

Нужны обе вселенные. Маркеры Undertale — только имена и топонимы, они
однозначны, поэтому одного достаточно.

Что сюда НЕ входит и почему:
- «подземелье» — общефэнтезийное слово, срабатывало в 98 заметках;
- «determination» / «решимость» — обычное слово, 52 заметки;
- «Азгор» обязан идти с границей начала слова, иначе находится внутри
  «р-азгор-ающийся» — 95 ложных срабатываний.
"""
import re

import _common

TAG = "dc/undertale"

DC_MARKERS = ["Бэтсемья", "Бэтпещера", "Готэм", "Бэтмен", "Джейсон", "Робин", "Брюс"]

UNDERTALE = [
    r"Undertale",
    r"Санс\b",
    r"Папирус\b",
    r"Ториэл\w*",
    r"Андайн",
    r"Азгор",
    r"Флауи",
    r"Фриск",
    r"Гастер",
    r"Меттатон",
    r"Азриэль",
    r"Меркурий\s+Подземель",
    r"Водопадь\w*",
    r"Сноудин",
    r"Хотленд",
]


def check(text):
    if not text:
        return False
    if not _common.search_any(DC_MARKERS, text):
        return False
    return _common.search_any(UNDERTALE, text)
