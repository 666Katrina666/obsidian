"""#MahouShoujo - жанр махо-сёдзё или явная франшиза.

Названия франшиз самодостаточны: «Tokyo Mew Mew» в заметке — это уже
кроссовер, второго маркера ждать неоткуда. Раньше порог был «2 разных
маркера», и заметки вроде «372. Tokyo Mew Mew Crossover» тег не получали:
«Tokyo Mew» и «Tokyo Mew Mew» — один и тот же маркер, а больше в тексте
ничего жанрового нет.

Общие слова (преображение, контракт, питомец, медальон, кристалл) сюда
не входят — они встречаются в любой магической истории.
"""
import re

import _common

TAG = "MahouShoujo"

# Франшизы и прямое название жанра — по одному достаточно.
FRANCHISE = [
    r"Sailor Moon", r"Сейлор Мун",
    r"Pretty Cure", r"Прети Кюр", r"Прекрасная Кюр", r"Cure\s",
    r"Tokyo Mew Mew", r"Tokyo Mew", r"Токио Мяу Мяу",
    r"W\.I\.T\.C\.H", r"В\.И\.Т\.Ч",
    r"Cardcaptor", r"Кардкоптор",
    r"mahou shoujo", r"magical girl", r"махо-сёдзё",
    r"магическая девочка", r"магический мальчик",
]

# Жанровые обороты: поодиночке слабоваты, нужны два разных.
GENRE = [
    r"в магическую форму",
    r"превращается в магического воина",
    r"магические карты",
    r"медальон.*магическ|магическ.*медальон",
    r"магическ\w*\s+трансформац",
    r"боевой костюм.*магическ",
]


def check(text):
    if not text:
        return False
    if _common.search_any(FRANCHISE, text):
        return True
    return _common.count_distinct(GENRE, text) >= 2
