# -*- coding: utf-8 -*-
"""#reveal - раскрытие тайны или личности.

Устройство: сильные маркеры — по одному достаточно, потому что каждый
сам по себе описывает ровно раскрытие («раскрытие личности», «секрет
раскрыт», «снял маску»).

Голые «раскрыл» и «раскрытие» из критерия убраны намеренно. Они ловили
что угодно: в «11. Dragonwake» тег держался на фразе «раскрылись шипастые
пластины, похожие на раскрытую пасть вулкана». Раньше это компенсировалось
порогом «2+ маркера», но порог был фиктивным — семь форм слова «раскрытие»
засчитывались как разные маркеры, так что хватало одного упоминания.
"""
import re

import _common

TAG = "reveal"

# \w* — из-за склонений: «раскрытие/раскрытия/раскрытием личности».
STRONG = [
    r"раскрыти\w*\s+(?:свое[йго]\s+)?личност",
    r"раскрыти\w*\s+идентичност",
    r"раскрыти\w*\s+тайн",
    r"раскрыти\w*\s+секрет",
    r"раскрыти\w*\s+правд",
    # Без «себя» и без несовершенного вида: «раскрывать себя» — это
    # эмоциональная открытость, а не раскрытие тайны. На нём одном
    # набиралось 62 лишние заметки.
    # До двух слов между глаголом и объектом: «раскрыла его секрет»,
    # «раскрыл всю правду о себе».
    r"раскры(?:л|ла|ли|ть)\w*\s+(?:[\w-]+\s+){0,2}?(?:тайн|секрет|личност|правд|природ)",
    # «правда раскрылась», «заговор раскрыт», «имя пока не раскрыто»
    r"(?:правд|тайн|секрет|заговор|личност|имя|обман)\w*\s+(?:[\w-]+\s+){0,3}?(?:не\s+)?раскры",
    r"личност\w*\s+раскрыт",
    r"идентичност\w*\s+раскрыт",
    r"тайн\w*\s+раскрыт",
    r"секрет\w*\s+раскрыт",
    r"секрет\w*\s+открыл",
    r"тайн\w*\s+выплыл",
    r"правд\w*\s+вскрыл",
    r"маск\w*\s+снят",
    r"сн(?:ял|яла|яли|ять)\w*\s+маску",
    r"сорвал\w*\s+маску",
    r"разоблачени\w*",
    r"разоблачил\w*",
    r"узнал\w*,?\s+кто\s+(?:он|она)",
    r"узнал\w*\s+(?:всю\s+)?правду",
    r"identity reveal",
    r"secret revealed",
    # Раскрытие как событие сюжета: «момент раскрытия», «боится раскрытия»,
    # «после раскрытия». Само слово «раскрытие» тут уже про тайну, а не про
    # раскрывшиеся пластины — его определяет соседнее слово.
    r"(?:момент|сцен|эпизод|глав)\w*\s+раскрыти",
    r"(?:до|после|перед)\s+раскрыти",
    r"(?:страх|боит|боял|бояться|ждал|ждёт|риск|рисков)\w*\s+раскрыти",
    r"раскрыти\w*\s+(?:прошло|случилось|произошло|неизбежно)",
]


def check(text):
    if not text:
        return False
    return _common.search_any(STRONG, text)
